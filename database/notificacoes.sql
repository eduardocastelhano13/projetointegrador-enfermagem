-- ============================================================================
-- CONECTA – Notificações (tarefas, provas, lembretes e avisos de atividades)
-- Execute este arquivo inteiro no Supabase: SQL Editor > New query > Run.
-- Pode ser executado mais de uma vez sem duplicar nada.
--
-- Eventos que geram notificação (todos reais, nenhum de demonstração):
--   * professor cria tarefa ou prova            -> "Nova tarefa" / "Nova prova"   (todos os alunos)
--   * professor cadastra um paciente           -> "Novo paciente"
--   * professor cria um caso clínico            -> "Novo caso clínico"
--   * professor muda o prazo/data               -> "Prazo alterado" / "Data da prova alterada"
--   * professor anexa material a uma atividade  -> "Novo material"
--   * prova se aproximando (7 dias, 1 dia, 1 h) -> "Prova se aproximando"
--   * lembrete perto da hora (antecedência escolhida ao criar) -> "Lembrete"
-- ============================================================================

-- 1) Tabela de notificações ---------------------------------------------------
create table if not exists public.notificacoes (
  id              bigint generated by default as identity primary key,
  destinatario_id uuid not null references public.perfis(id) on delete cascade,
  tipo            text not null,
  titulo          text not null,
  mensagem        text,
  link            text,
  atividade_id    bigint,
  criado_em       timestamptz not null default now(),
  lida_em         timestamptz
);

alter table public.notificacoes add column if not exists lembrete_id text;
-- "chave" identifica o EVENTO que gerou o aviso; é ela que impede duplicatas
alter table public.notificacoes add column if not exists chave text;

-- o tipo aceita 'prova', 'atividade', 'lembrete', 'paciente' e 'caso'
do $$
declare r record;
begin
  for r in
    select conname from pg_constraint
    where conrelid = 'public.notificacoes'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%tipo%'
  loop
    execute format('alter table public.notificacoes drop constraint %I', r.conname);
  end loop;
end $$;
alter table public.notificacoes
  add constraint notificacoes_tipo_check check (tipo in ('prova', 'atividade', 'lembrete', 'paciente', 'caso'));

-- uma atividade pode gerar vários avisos (nova, prazo alterado, prova se aproximando...),
-- então a unicidade por atividade da versão anterior sai e entra a unicidade por evento
drop index if exists public.notificacoes_atividade_unica;
create unique index if not exists notificacoes_chave_unica
  on public.notificacoes (destinatario_id, chave) where chave is not null;
create unique index if not exists notificacoes_lembrete_unico
  on public.notificacoes (destinatario_id, lembrete_id) where lembrete_id is not null;
create index if not exists notificacoes_destinatario_idx
  on public.notificacoes (destinatario_id, criado_em desc);

-- 2) Antecedência escolhida ao criar o lembrete ---------------------------------
-- Minutos antes do horário em que a pessoa quer ser avisada (null = não avisar; 0 = na hora).
alter table public.lembretes add column if not exists avisar_antes_min integer;

-- 3) Segurança: cada pessoa lê e marca como lida só as próprias notificações --------
alter table public.notificacoes enable row level security;

drop policy if exists notificacoes_ler_proprias on public.notificacoes;
create policy notificacoes_ler_proprias on public.notificacoes
  for select to authenticated using (destinatario_id = auth.uid());

drop policy if exists notificacoes_atualizar_proprias on public.notificacoes;
create policy notificacoes_atualizar_proprias on public.notificacoes
  for update to authenticated
  using (destinatario_id = auth.uid()) with check (destinatario_id = auth.uid());

-- quem está logado só altera a coluna "lida_em" (as notificações nascem por gatilho/função)
revoke insert, update, delete on public.notificacoes from anon, authenticated;
grant select on public.notificacoes to authenticated;
grant update (lida_em) on public.notificacoes to authenticated;

-- 4) Professor publica tarefa/prova -> um aviso para cada aluno ------------------
create or replace function public.notificar_nova_atividade()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_prova boolean := (new.tipo = 'prova');
  v_prazo text := to_char(new.data_limite at time zone 'America/Sao_Paulo', 'DD/MM/YYYY "às" HH24:MI');
begin
  insert into public.notificacoes (destinatario_id, tipo, titulo, mensagem, link, atividade_id, chave)
  select p.id,
         case when v_prova then 'prova' else 'atividade' end,
         case when v_prova then 'Nova prova' else 'Nova tarefa' end,
         new.titulo || case when v_prova then ' · prova em ' else ' · prazo ' end || v_prazo,
         '#/atividades/' || new.id::text,
         new.id,
         'atividade:' || new.id::text || ':nova'
  from public.perfis p
  where p.papel = 'aluno'
  on conflict do nothing;
  return new;
end $$;

drop trigger if exists trg_notificar_nova_atividade on public.atividades;
create trigger trg_notificar_nova_atividade
  after insert on public.atividades
  for each row execute function public.notificar_nova_atividade();

-- professor muda o prazo/data -> aviso (um por nova data, sem repetir)
create or replace function public.notificar_prazo_alterado()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_prova boolean := (new.tipo = 'prova');
  v_data text := to_char(new.data_limite at time zone 'America/Sao_Paulo', 'DD/MM/YYYY "às" HH24:MI');
begin
  insert into public.notificacoes (destinatario_id, tipo, titulo, mensagem, link, atividade_id, chave)
  select p.id,
         case when v_prova then 'prova' else 'atividade' end,
         case when v_prova then 'Data da prova alterada' else 'Prazo alterado' end,
         new.titulo || ' · agora ' || v_data,
         '#/atividades/' || new.id::text,
         new.id,
         'atividade:' || new.id::text || ':prazo:' || extract(epoch from new.data_limite)::bigint::text
  from public.perfis p
  where p.papel = 'aluno'
  on conflict do nothing;
  return new;
end $$;

drop trigger if exists trg_notificar_prazo_alterado on public.atividades;
create trigger trg_notificar_prazo_alterado
  after update of data_limite on public.atividades
  for each row
  when (old.data_limite is distinct from new.data_limite)
  execute function public.notificar_prazo_alterado();

-- professor anexa material de apoio a uma atividade -> aviso
-- (não repete o aviso quando o anexo é enviado junto com a criação da atividade)
create or replace function public.notificar_novo_material()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare a record;
begin
  if new.atividade_id is null then
    return new;
  end if;
  select av.id, av.titulo, av.tipo into a from public.atividades av where av.id = new.atividade_id;
  if not found then
    return new;
  end if;
  insert into public.notificacoes (destinatario_id, tipo, titulo, mensagem, link, atividade_id, chave)
  select p.id,
         case when a.tipo = 'prova' then 'prova' else 'atividade' end,
         'Novo material',
         a.titulo || ' · ' || coalesce(new.titulo, 'material de apoio'),
         '#/atividades/' || a.id::text,
         a.id,
         'anexo:' || new.id::text
  from public.perfis p
  where p.papel = 'aluno'
    and not exists (
      select 1 from public.notificacoes n
      where n.destinatario_id = p.id
        and n.chave = 'atividade:' || a.id::text || ':nova'
        and n.criado_em > now() - interval '2 minutes'
    )
  on conflict do nothing;
  return new;
end $$;

drop trigger if exists trg_notificar_novo_material on public.anexos;
create trigger trg_notificar_novo_material
  after insert on public.anexos
  for each row execute function public.notificar_novo_material();

