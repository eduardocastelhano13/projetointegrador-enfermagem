-- 5) Avisos que dependem do relógio ---------------------------------------------
-- 5a) Lembretes perto da hora. Cria o aviso quando (data + hora) - antecedência já passou.
-- Sem horário, a referência é 08:00. Lembretes gerais (sem aluno) avisam todos os alunos.
create or replace function public.gerar_notificacoes_lembretes()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  with base as (
    select l.id, l.titulo, l.aluno_id, l.hora, l.avisar_antes_min,
           (l.data_lembrete + coalesce(l.hora, time '08:00')) at time zone 'America/Sao_Paulo' as quando
    from public.lembretes l
    where l.avisar_antes_min is not null
      and l.data_lembrete >= ((now() at time zone 'America/Sao_Paulo')::date - 1)
  ),
  devidos as (
    select b.*,
           ceil(extract(epoch from (b.quando - now())) / 60)::int as faltam_min
    from base b
    where now() >= b.quando - make_interval(mins => b.avisar_antes_min)
      and now() <= b.quando + interval '6 hours'
  ),
  novos as (
    insert into public.notificacoes (destinatario_id, tipo, titulo, mensagem, link, lembrete_id, chave)
    select p.id,
           'lembrete',
           'Lembrete',
           d.titulo || ' · ' ||
           case
             when d.faltam_min <= 0 then 'Está na hora'
             when d.faltam_min < 60 then 'Faltam ' || d.faltam_min || ' min'
             when d.faltam_min < 1440 then 'Faltam ' || ceil(d.faltam_min / 60.0)::int || ' h'
             else 'Faltam ' || ceil(d.faltam_min / 1440.0)::int || ' dia(s)'
           end
           || ' · ' || to_char(d.quando at time zone 'America/Sao_Paulo', 'DD/MM')
           || case when d.hora is not null
                   then ' às ' || to_char(d.quando at time zone 'America/Sao_Paulo', 'HH24:MI')
                   else '' end,
           '#/',
           d.id::text,
           'lembrete:' || d.id::text
    from devidos d
    join public.perfis p on p.papel = 'aluno' and (d.aluno_id is null or p.id = d.aluno_id)
    on conflict do nothing
    returning 1
  )
  select count(*) into n from novos;
  return n;
end $$;

-- 5b) Prova se aproximando, conforme a data real cadastrada: 7 dias, 1 dia e 1 hora antes.
-- Só vale o marco mais próximo que já chegou (nunca dispara dois de uma vez) e não repete o
-- "Nova prova" quando a prova acabou de ser criada. Se a data mudar, os marcos recomeçam.
create or replace function public.gerar_notificacoes_provas()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  with marcos(marco, intervalo) as (
    values ('7d', interval '7 days'), ('1d', interval '1 day'), ('1h', interval '1 hour')
  ),
  devidas as (
    select a.id, a.titulo, a.data_limite, m.marco,
           a.data_limite - m.intervalo as gatilho,
           row_number() over (partition by a.id order by (a.data_limite - m.intervalo) desc) as rn
    from public.atividades a
    cross join marcos m
    where a.tipo = 'prova'
      and a.data_limite > now()
      and now() >= a.data_limite - m.intervalo
  ),
  atuais as (
    select d.*,
           ((d.data_limite at time zone 'America/Sao_Paulo')::date
             - (now() at time zone 'America/Sao_Paulo')::date) as dias
    from devidas d
    where d.rn = 1
  ),
  novos as (
    insert into public.notificacoes (destinatario_id, tipo, titulo, mensagem, link, atividade_id, chave)
    select p.id,
           'prova',
           'Prova se aproximando',
           a.titulo || ' · ' ||
           case when a.dias <= 0 then 'hoje' when a.dias = 1 then 'amanhã' else 'em ' || a.dias || ' dias' end
           || ' (' || to_char(a.data_limite at time zone 'America/Sao_Paulo', 'DD/MM "às" HH24:MI') || ')',
           '#/atividades/' || a.id::text,
           a.id,
           'prova:' || a.id::text || ':' || a.marco || ':' || extract(epoch from a.data_limite)::bigint::text
    from atuais a
    join public.perfis p on p.papel = 'aluno'
    where not exists (
      select 1 from public.notificacoes x
      where x.destinatario_id = p.id
        and x.chave = 'atividade:' || a.id::text || ':nova'
        and x.criado_em > a.gatilho
    )
    on conflict do nothing
    returning 1
  )
  select count(*) into n from novos;
  return n;
end $$;

-- 5c) Ponto único chamado pelo painel do aluno (a cada ~30 s) e, se quiser, pelo pg_cron
create or replace function public.gerar_notificacoes_automaticas()
returns integer
language plpgsql
security definer
set search_path = public
as $$
begin
  return public.gerar_notificacoes_lembretes() + public.gerar_notificacoes_provas();
end $$;

revoke all on function public.gerar_notificacoes_lembretes() from public, anon;
revoke all on function public.gerar_notificacoes_provas() from public, anon;
revoke all on function public.gerar_notificacoes_automaticas() from public, anon;
grant execute on function public.gerar_notificacoes_lembretes() to authenticated;
grant execute on function public.gerar_notificacoes_automaticas() to authenticated;

-- lembrete editado (data, hora ou antecedência) ou excluído -> o aviso antigo sai e um novo
-- é gerado quando chegar a hora certa
create or replace function public.limpar_notificacoes_lembrete()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.notificacoes where lembrete_id = old.id::text;
  return coalesce(new, old);
end $$;

drop trigger if exists trg_limpar_notificacoes_lembrete_upd on public.lembretes;
create trigger trg_limpar_notificacoes_lembrete_upd
  after update of data_lembrete, hora, avisar_antes_min on public.lembretes
  for each row execute function public.limpar_notificacoes_lembrete();

drop trigger if exists trg_limpar_notificacoes_lembrete_del on public.lembretes;
create trigger trg_limpar_notificacoes_lembrete_del
  after delete on public.lembretes
  for each row execute function public.limpar_notificacoes_lembrete();

-- 6) Tempo real: o aviso aparece na hora, sem recarregar a página -------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notificacoes'
     ) then
    alter publication supabase_realtime add table public.notificacoes;
  end if;
end $$;

